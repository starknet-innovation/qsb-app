// Generated imports work in both Vite and the Lambda esbuild bundle.
import { readdirSync, writeFileSync } from "node:fs";
const dir = new URL("../src/lib/releases/", import.meta.url);
const files = readdirSync(dir)
  .filter(
    (name) => name.endsWith(".json") && name !== "qsb-config-a-ranked-v2.json",
  )
  .sort();
for (const file of files)
  if (!/^[a-z0-9-]+\.json$/.test(file))
    throw new Error("Invalid descriptor filename");
const imports = files.map(
  (file, i) => `import d${i} from ${JSON.stringify("./" + file)};`,
);
writeFileSync(
  new URL("registry.generated.ts", dir),
  "// Generated by scripts/generate-solver-registry.mjs; do not edit.\n" +
    imports.join("\n") +
    "\nexport default [" +
    files.map((_, i) => `d${i}`).join(", ") +
    "] as unknown[];\n",
);
